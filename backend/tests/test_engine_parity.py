"""The Python engine must produce exactly what the original TypeScript engine produced.

tests/fixtures/engine_golden.json was generated by running the TypeScript engine (v1.0.0) on the
hand-labelled evaluation dataset and on every open seed requirement.
"""

from __future__ import annotations

import json
from datetime import UTC, datetime
from pathlib import Path

import pytest

from app.schemas.entities import Listing, Organization, Requirement
from app.services.matching.engine import run_matching

GOLDEN = json.loads((Path(__file__).parent / "fixtures" / "engine_golden.json").read_text())
NOW = datetime(2026, 11, 24, tzinfo=UTC)
SEED = json.loads((Path(__file__).parents[1] / "app" / "seed" / "seed_data.json").read_text())


def _dump(result) -> dict:
    out = result.model_dump()
    if out.get("over_budget_alternative") is None:
        out.pop("over_budget_alternative", None)
    return out


def _orgs() -> dict[str, Organization]:
    rows = GOLDEN["eval_organizations"] + SEED["organizations"]
    return {o["id"]: Organization.model_validate(o) for o in rows}


EVAL_LISTINGS = [Listing.model_validate(l) for l in GOLDEN["eval_listings"]]


@pytest.mark.parametrize("case", GOLDEN["eval_cases"], ids=lambda c: c["label"]["requirement"]["id"])
def test_evaluation_dataset_matches_typescript(case):
    req = Requirement.model_validate(case["label"]["requirement"])
    result = run_matching(req, EVAL_LISTINGS, _orgs().get(req.organization_id), now=NOW)
    assert _dump(result) == case["result"]


@pytest.mark.parametrize("case", GOLDEN["seed_cases"], ids=lambda c: c["requirement"]["id"])
def test_seed_requirements_match_typescript(case):
    req = Requirement.model_validate(case["requirement"])
    listings = [Listing.model_validate(l) for l in SEED["listings"] if l["material_family"] == req.material_family]
    result = run_matching(req, listings, _orgs().get(req.organization_id), now=NOW)
    assert _dump(result) == case["result"]
