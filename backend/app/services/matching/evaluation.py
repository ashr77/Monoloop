"""MONOLOOP vs name-only baseline evaluation (execution plan §14, proposal §11).

Dataset: app/seed/evaluation_dataset.json — 35 listings, 12 requirements, ground truth labelled
by hand from the material rules (not generated by the engine).

Metrics: compatibility precision/recall, fulfilment claims (and false claims), pieces allocated
from incompatible or unavailable stock, and estimated delivered cost of fulfilled requirements.
"""

from __future__ import annotations

import json
from datetime import UTC, datetime
from functools import lru_cache
from pathlib import Path

from pydantic import BaseModel

from app.schemas.entities import Listing, Requirement
from app.services.matching.baseline import baseline_allocate, baseline_matches
from app.services.matching.engine import run_matching
from app.services.matching.rules import available_quantity

DATASET = Path(__file__).resolve().parents[2] / "seed" / "evaluation_dataset.json"
EVAL_NOW = datetime(2026, 11, 24, tzinfo=UTC)


class MethodMetrics(BaseModel):
    suggested: int
    truePositives: int  # noqa: N815 - names match the original report contract
    precision: float
    recall: float
    fulfilledClaims: int  # noqa: N815
    correctFulfilments: int  # noqa: N815
    falseFulfilmentClaims: int  # noqa: N815
    allocationErrorPieces: int  # noqa: N815


class MonoloopMetrics(MethodMetrics):
    estimatedCostOfFulfilledBdt: float  # noqa: N815


class EvaluationReport(BaseModel):
    requirements: int
    listings: int
    fulfillableByLabel: int  # noqa: N815
    monoloop: MonoloopMetrics
    baseline: MethodMetrics
    perRequirement: list[dict]  # noqa: N815


@lru_cache
def load_dataset() -> tuple[list[dict], list[Listing]]:
    data = json.loads(DATASET.read_text(encoding="utf-8"))
    return data["requirements"], [Listing.model_validate(l) for l in data["listings"]]


def _ratio(a: float, b: float) -> float:
    return 1 if b == 0 else a / b


def _allocation_errors(lines: list[tuple[str, int]], truth: set[str], by_id: dict[str, Listing]) -> int:
    """Pieces taken from an incompatible listing, or beyond its unreserved stock."""
    errors = 0
    for listing_id, qty in lines:
        errors += qty if listing_id not in truth else max(0, qty - available_quantity(by_id[listing_id]))
    return errors


def evaluate() -> EvaluationReport:
    labelled, listings = load_dataset()
    by_id = {l.id: l for l in listings}
    m = {"suggested": 0, "tp": 0, "truth": 0, "claims": 0, "correct": 0, "errors": 0, "cost": 0.0}
    b = {"suggested": 0, "tp": 0, "claims": 0, "correct": 0, "errors": 0}
    per = []
    for item in labelled:
        req = Requirement.model_validate(item["requirement"])
        truth = set(item["compatible"])
        m["truth"] += len(truth)

        result = run_matching(req, listings, now=EVAL_NOW)
        compatible = [e.listing_id for e in result.evaluations if e.compatible]
        m["suggested"] += len(compatible)
        m["tp"] += sum(1 for i in compatible if i in truth)
        claimed = result.matching_status in ("EXACT_MATCH", "MULTI_SUPPLIER_MATCH")
        if claimed:
            m["claims"] += 1
            m["correct"] += 1 if item["fulfillable"] else 0
            m["cost"] += result.total_estimated_cost_bdt
        m["errors"] += _allocation_errors([(a.listing_id, a.allocated_quantity) for a in result.allocations], truth, by_id)

        suggested = [l.id for l in baseline_matches(req, listings)]
        b["suggested"] += len(suggested)
        b["tp"] += sum(1 for i in suggested if i in truth)
        lines = baseline_allocate(req, listings)
        baseline_claimed = sum(l["quantity"] for l in lines) >= req.required_quantity
        if baseline_claimed:
            b["claims"] += 1
            b["correct"] += 1 if item["fulfillable"] else 0
        b["errors"] += _allocation_errors([(l["listing_id"], l["quantity"]) for l in lines], truth, by_id)

        per.append({
            "id": req.id, "truth": item["compatible"],
            "monoloop": {"compatible": compatible, "status": result.matching_status, "allocated": result.allocated_quantity},
            "baseline": {"suggested": suggested, "claimedFulfilled": baseline_claimed},
        })

    def metrics(x: dict) -> dict:
        return {
            "suggested": x["suggested"], "truePositives": x["tp"], "precision": _ratio(x["tp"], x["suggested"]),
            "recall": _ratio(x["tp"], m["truth"]), "fulfilledClaims": x["claims"], "correctFulfilments": x["correct"],
            "falseFulfilmentClaims": x["claims"] - x["correct"], "allocationErrorPieces": x["errors"],
        }

    return EvaluationReport(
        requirements=len(labelled),
        listings=len(listings),
        fulfillableByLabel=sum(1 for x in labelled if x["fulfillable"]),
        monoloop=MonoloopMetrics(**metrics(m), estimatedCostOfFulfilledBdt=m["cost"]),
        baseline=MethodMetrics(**metrics(b)),
        perRequirement=per,
    )
